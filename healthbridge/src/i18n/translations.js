// For languages without full translations, fall back to English
// but show the native language name in the selector
export const getFallbackTranslations = (langCode) => {
  const lang = LANGUAGES.find(l => l.code === langCode);
  return {
    ...translations.en,
    selectLanguage: translations[langCode]?.selectLanguage || "Select Language",
    appName: "HealthBridge Universal",
    tagline: translations[langCode]?.tagline || "Healthcare for Everyone",
  };
};

export const t = (lang, key) => {
  const dict = translations[lang] || getFallbackTranslations(lang);
  return dict[key] || translations.en[key] || key;
};

export const getDir = (langCode) => {
  const lang = LANGUAGES.find(l => l.code === langCode);
  return lang?.dir || "ltr";
};

export const detectBrowserLanguage = () => {
  const browserLang = navigator.language?.split('-')[0] || 'en';
  const supported = LANGUAGES.find(l => l.code === browserLang);
  return supported ? browserLang : 'en';
};
